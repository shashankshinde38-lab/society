const STORAGE_KEY_PREFIX = "parijat_erp_v5_";

function getStoredItem<T>(key: string, defaultValue: T): T {
  if (typeof window === "undefined") return defaultValue;
  try {
    const item = window.localStorage.getItem(STORAGE_KEY_PREFIX + key);
    return item ? JSON.parse(item) : defaultValue;
  } catch {
    return defaultValue;
  }
}

function setStoredItem<T>(key: string, value: T): void {
  if (typeof window === "undefined") return;
  try {
    window.localStorage.setItem(STORAGE_KEY_PREFIX + key, JSON.stringify(value));
  } catch (e) {
    console.error("Storage error:", e);
  }
}

// Generate 12-month calendar slots for all flats for a given year.
// Fresh flats/slots default to NO_DUES (due_amount: 0, paid_amount: 0).
// Dues only accumulate when explicitly generated by admin.
function generateYearlyInvoices(flats: Flat[], year: number = 2026, monthlyAmt: number = 1100): MaintenanceInvoice[] {
  const invoices: MaintenanceInvoice[] = [];

  flats.forEach((flat) => {
    for (let m = 1; m <= 12; m++) {
      const amt = flat.maintenance_override || monthlyAmt;
      invoices.push({
        id: `inv-${flat.id}-${year}-${m}`,
        flat_id: flat.id,
        resident_id: null,
        month: m,
        year,
        invoice_amount: amt,
        paid_amount: 0,
        due_amount: 0, // Starts at 0 until maintenance dues are generated
        status: "NO_DUES", // Default status for new flat: No Dues
        due_date: `${year}-${String(m).padStart(2, "0")}-10`,
        created_at: new Date().toISOString(),
        updated_at: new Date().toISOString(),
      });
    }
  });

  return invoices;
}

export const DataStorage = {
  // --- SOCIETY ---
  getSociety(): Society {
    return getStoredItem("society", initialSociety);
  },
  updateSociety(data: Partial<Society>): Society {
    const current = this.getSociety();
    const updated = { ...current, ...data, updated_at: new Date().toISOString() };
    setStoredItem("society", updated);
    return updated;
  },

  // --- SETTINGS & RATE HISTORY ---
  getSettings(): MaintenanceSettings {
    return getStoredItem("settings", initialSettings);
  },
  updateSettings(data: Partial<MaintenanceSettings>): MaintenanceSettings {
    const current = this.getSettings();
    const updated = { ...current, ...data, updated_at: new Date().toISOString() };
    setStoredItem("settings", updated);
    return updated;
  },
  getRateHistory(): MaintenanceRateHistory[] {
    return getStoredItem("rate_history", [
      {
        id: "rh-1",
        society_id: "soc-parijat-a-wing",
        amount: 1100.0,
        effective_from: "2025-09-01",
        effective_to: null,
        reason: "Initial baseline society rate per flat",
        created_at: "2025-09-01T00:00:00Z",
      },
    ]);
  },
  addRateChange(newAmount: number, reason: string): MaintenanceRateHistory {
    const history = this.getRateHistory();
    const now = new Date();
    // Effective from 1st of next month
    const nextMonth = new Date(now.getFullYear(), now.getMonth() + 1, 1);
    const effectiveFrom = nextMonth.toISOString().split("T")[0];

    // Close previous active rate
    if (history.length > 0 && !history[history.length - 1].effective_to) {
      history[history.length - 1].effective_to = new Date(now.getFullYear(), now.getMonth() + 1, 0)
        .toISOString()
        .split("T")[0];
    }

    const newRecord: MaintenanceRateHistory = {
      id: "rh-" + Date.now(),
      society_id: "soc-parijat-a-wing",
      amount: newAmount,
      effective_from: effectiveFrom,
      effective_to: null,
      reason,
      created_at: now.toISOString(),
    };

    history.push(newRecord);
    setStoredItem("rate_history", history);
    this.updateSettings({ monthly_amount: newAmount });
    return newRecord;
  },

  // --- FLOORS ---
  getFloors(): Floor[] {
    const floors = getStoredItem("floors", initialFloors);
    const flats = this.getFlats();
    return floors.map((f) => ({
      ...f,
      total_flats: flats.filter((flat) => flat.floor_id === f.id).length,
    }));
  },
  addFloor(floorData: Omit<Floor, "id" | "society_id" | "created_at" | "updated_at">): Floor {
    const floors = this.getFloors();
    const newFloor: Floor = {
      ...floorData,
      id: "floor-" + Date.now(),
      society_id: "soc-parijat-a-wing",
      created_at: new Date().toISOString(),
      updated_at: new Date().toISOString(),
    };
    floors.push(newFloor);
    setStoredItem("floors", floors);
    return newFloor;
  },
  updateFloor(id: string, data: Partial<Floor>): Floor {
    const floors = this.getFloors();
    const idx = floors.findIndex((f) => f.id === id);
    if (idx === -1) throw new Error("Floor not found");
    floors[idx] = { ...floors[idx], ...data, updated_at: new Date().toISOString() };
    setStoredItem("floors", floors);
    return floors[idx];
  },
  deleteFloor(id: string): void {
    const flats = this.getFlats();
    const hasFlats = flats.some((f) => f.floor_id === id);
    if (hasFlats) {
      throw new Error("Cannot delete floor with assigned flats. Reassign or delete flats first.");
    }
    const floors = this.getFloors().filter((f) => f.id !== id);
    setStoredItem("floors", floors);
  },

  // --- FLATS ---
  getFlats(): Flat[] {
    const flats = getStoredItem("flats", initialFlats);
    const floors = getStoredItem("floors", initialFloors);
    const residents = this.getResidents();
    const invoices = this.getInvoices();

    return flats.map((flat) => {
      const floor = floors.find((fl) => fl.id === flat.floor_id);
      const resident = residents.find((r) => r.flat_id === flat.id && r.is_active);
      const flatInvoices = invoices.filter((i) => i.flat_id === flat.id);
      const outstandingDues = flatInvoices
        .filter((inv) => inv.status === "UNPAID" || inv.status === "PARTIAL")
        .reduce((sum, inv) => sum + Number(inv.due_amount || 0), 0);
      const advanceBalance = this.getFlatAdvanceBalance(flat.id);

      return {
        ...flat,
        floor,
        current_resident: resident || null,
        outstanding_dues: outstandingDues,
        advance_balance: advanceBalance,
      };
    });
  },
  addFlat(flatData: Omit<Flat, "id" | "society_id" | "created_at" | "updated_at">): Flat {
    const flats = this.getFlats();
    const exists = flats.some((f) => f.flat_number.toUpperCase() === flatData.flat_number.toUpperCase());
    if (exists) throw new Error(`Flat number ${flatData.flat_number} already exists!`);

    const newFlat: Flat = {
      ...flatData,
      id: "flat-" + Date.now(),
      society_id: "soc-parijat-a-wing",
      created_at: new Date().toISOString(),
      updated_at: new Date().toISOString(),
    };
    flats.push(newFlat);
    setStoredItem("flats", flats);

    // Also auto-generate invoices for new flat
    const allInvoices = this.getInvoices();
    const newInvoices = generateYearlyInvoices([newFlat], 2026, 1100);
    setStoredItem("invoices", [...allInvoices, ...newInvoices]);

    return newFlat;
  },
  updateFlat(id: string, data: Partial<Flat>): Flat {
    const flats = this.getFlats();
    const idx = flats.findIndex((f) => f.id === id);
    if (idx === -1) throw new Error("Flat not found");
    flats[idx] = { ...flats[idx], ...data, updated_at: new Date().toISOString() };
    setStoredItem("flats", flats);
    return flats[idx];
  },
  deleteFlat(id: string): void {
    const flats = this.getFlats().filter((f) => f.id !== id);
    setStoredItem("flats", flats);
  },

  // --- RESIDENTS & OCCUPANCY HISTORY ---
  getResidents(): Resident[] {
    return getStoredItem("residents", initialResidents);
  },
  getResidentHistory(flatId?: string): FlatResidentHistory[] {
    const history = getStoredItem<FlatResidentHistory[]>("resident_history", []);
    if (flatId) return history.filter((h) => h.flat_id === flatId);
    return history;
  },
  addResident(data: Omit<Resident, "id" | "is_active" | "created_at" | "updated_at">): Resident {
    const residents = this.getResidents();
    const newResident: Resident = {
      ...data,
      id: "res-" + Date.now(),
      is_active: true,
      created_at: new Date().toISOString(),
      updated_at: new Date().toISOString(),
    };
    residents.push(newResident);
    setStoredItem("residents", residents);

    // Set flat to OCCUPIED
    this.updateFlat(data.flat_id, { status: "OCCUPIED" });
    return newResident;
  },
  changeResidentOccupant(
    flatId: string,
    newResidentData: {
      full_name: string;
      resident_type: "OWNER" | "TENANT";
      email?: string;
      mobile: string;
      move_in_date: string;
      notes?: string;
    }
  ): { current: Resident; archived: FlatResidentHistory } {
    const residents = this.getResidents();
    const history = this.getResidentHistory();
    const currentResIdx = residents.findIndex((r) => r.flat_id === flatId && r.is_active);

    let archivedRecord: FlatResidentHistory;

    if (currentResIdx !== -1) {
      const prior = residents[currentResIdx];
      archivedRecord = {
        id: "hist-" + Date.now(),
        flat_id: flatId,
        resident_name: prior.full_name,
        resident_type: prior.resident_type,
        email: prior.email,
        mobile: prior.mobile,
        move_in_date: prior.move_in_date,
        move_out_date: newResidentData.move_in_date,
        changed_at: new Date().toISOString(),
        notes: newResidentData.notes || `Replaced by ${newResidentData.full_name} (${newResidentData.resident_type})`,
      };
      history.push(archivedRecord);
      setStoredItem("resident_history", history);

      // Deactivate prior
      residents[currentResIdx].is_active = false;
      residents[currentResIdx].move_out_date = newResidentData.move_in_date;
    } else {
      archivedRecord = {
        id: "hist-" + Date.now(),
        flat_id: flatId,
        resident_name: "Vacant",
        resident_type: "OWNER",
        email: null,
        mobile: null,
        move_in_date: null,
        move_out_date: newResidentData.move_in_date,
        changed_at: new Date().toISOString(),
        notes: "Flat transitioned from vacant to occupied",
      };
    }

    // Create new active resident
    const newResident: Resident = {
      id: "res-" + Date.now(),
      flat_id: flatId,
      full_name: newResidentData.full_name,
      resident_type: newResidentData.resident_type,
      email: newResidentData.email || null,
      mobile: newResidentData.mobile,
      alternate_mobile: null,
      move_in_date: newResidentData.move_in_date,
      move_out_date: null,
      is_active: true,
      created_at: new Date().toISOString(),
      updated_at: new Date().toISOString(),
    };
    residents.push(newResident);
    setStoredItem("residents", residents);

    this.updateFlat(flatId, { status: "OCCUPIED" });
    return { current: newResident, archived: archivedRecord };
  },

  // --- ADVANCE POOL & WALLET SYSTEM ---
  getAdvanceBalances(): Record<string, number> {
    return getStoredItem<Record<string, number>>("advance_balances", {});
  },
  getFlatAdvanceBalance(flatId: string): number {
    const balances = this.getAdvanceBalances();
    return Number(balances[flatId] || 0);
  },
  setFlatAdvanceBalance(flatId: string, amount: number): void {
    const balances = this.getAdvanceBalances();
    balances[flatId] = Math.max(0, amount);
    setStoredItem("advance_balances", balances);
  },
  getTotalAdvancePool(): number {
    const balances = this.getAdvanceBalances();
    return Object.values(balances).reduce((sum, b) => sum + Number(b || 0), 0);
  },

  // --- INVOICES & MAINTENANCE CALENDAR ---
  getInvoices(flatId?: string, year: number = 2026): MaintenanceInvoice[] {
    let invoices = getStoredItem<MaintenanceInvoice[]>("invoices", []);
    if (!invoices || invoices.length === 0) {
      const flats = getStoredItem("flats", initialFlats);
      invoices = generateYearlyInvoices(flats, year, 1100);
      setStoredItem("invoices", invoices);
    }

    if (flatId) {
      return invoices.filter((i) => i.flat_id === flatId && i.year === year);
    }
    return invoices;
  },

  generateMonthlyDues(
    flatId: string,
    year: number,
    months: number[],
    customAmount?: number
  ): MaintenanceInvoice[] {
    const invoices = this.getInvoices();
    const flats = this.getFlats();
    const flat = flats.find((f) => f.id === flatId);
    const monthlyAmt = customAmount || flat?.maintenance_override || this.getSettings().monthly_amount || 1100;

    months.forEach((m) => {
      const existing = invoices.find((inv) => inv.flat_id === flatId && inv.year === year && inv.month === m);
      if (existing) {
        if (existing.status === "NO_DUES") {
          existing.status = "UNPAID";
          existing.invoice_amount = monthlyAmt;
          existing.due_amount = monthlyAmt;
          existing.paid_amount = 0;
          existing.updated_at = new Date().toISOString();
        }
      } else {
        invoices.push({
          id: `inv-${flatId}-${year}-${m}`,
          flat_id: flatId,
          resident_id: flat?.current_resident?.id || null,
          month: m,
          year,
          invoice_amount: monthlyAmt,
          paid_amount: 0,
          due_amount: monthlyAmt,
          status: "UNPAID",
          due_date: `${year}-${String(m).padStart(2, "0")}-10`,
          created_at: new Date().toISOString(),
          updated_at: new Date().toISOString(),
        });
      }
    });

    setStoredItem("invoices", invoices);
    return invoices.filter((i) => i.flat_id === flatId && i.year === year);
  },

  // --- PAYMENTS & ATOMIC ALLOCATION ---
  getPayments(): MaintenancePayment[] {
    return getStoredItem("payments", initialPayments);
  },
  recordPayment(data: {
    flatId: string;
    amountReceived: number;
    paymentMethod: MaintenancePayment["payment_method"];
    paymentDate: string;
    transactionRef?: string;
    description?: string;
    attachmentUrl?: string | null;
    selectedInvoiceIds?: string[];
  }): { payment: MaintenancePayment; receiptNo: string; advanceAllocated: number; allocatedMonths: string[] } {
    const payments = this.getPayments();
    const invoices = this.getInvoices();
    const flats = this.getFlats();
    const flat = flats.find((f) => f.id === data.flatId);
    if (!flat) throw new Error("Flat not found");

    const receiptNo =
      "REC-" +
      data.paymentDate.replace(/-/g, "").substring(0, 6) +
      "-" +
      Math.floor(1000 + Math.random() * 9000);

    let remaining = data.amountReceived;
    const MONTH_LABELS = [
      "Jan", "Feb", "Mar", "Apr", "May", "Jun",
      "Jul", "Aug", "Sep", "Oct", "Nov", "Dec"
    ];
    const allocatedMonths: string[] = [];

    // 1. Identify and sort target invoices
    let targetInvoices: MaintenanceInvoice[] = [];
    if (data.selectedInvoiceIds && data.selectedInvoiceIds.length > 0) {
      const selectedSet = new Set(data.selectedInvoiceIds);
      targetInvoices = invoices
        .filter((inv) => inv.flat_id === data.flatId && selectedSet.has(inv.id))
        .sort((a, b) => a.year - b.year || a.month - b.month);

      // If any selected invoice is in NO_DUES status, activate it for payment
      targetInvoices.forEach((inv) => {
        if (inv.status === "NO_DUES" || inv.due_amount === 0) {
          const amt = inv.invoice_amount || flat.maintenance_override || 1100;
          inv.status = "UNPAID";
          inv.invoice_amount = amt;
          inv.due_amount = amt;
          inv.paid_amount = 0;
        }
      });
    } else {
      targetInvoices = invoices
        .filter((inv) => inv.flat_id === data.flatId && (inv.status === "UNPAID" || inv.status === "PARTIAL"))
        .sort((a, b) => a.year - b.year || a.month - b.month);
    }

    // 2. Chronological allocation: earliest selected month first
    for (const inv of targetInvoices) {
      if (remaining <= 0) break;
      const due = Number(inv.due_amount);
      const mLabel = `${MONTH_LABELS[inv.month - 1]} ${inv.year}`;

      if (remaining >= due) {
        remaining -= due;
        inv.paid_amount = inv.invoice_amount;
        inv.due_amount = 0;
        inv.status = "PAID";
        inv.updated_at = new Date().toISOString();
        allocatedMonths.push(mLabel);
      } else {
        inv.paid_amount = Number(inv.paid_amount) + remaining;
        inv.due_amount = due - remaining;
        inv.status = "PARTIAL";
        inv.updated_at = new Date().toISOString();
        allocatedMonths.push(`${mLabel} (Part)`);
        remaining = 0;
      }
    }

    setStoredItem("invoices", invoices);

    // 3. Excess goes to advance balance
    const advanceAllocated = remaining;
    if (advanceAllocated > 0) {
      const currentAdv = this.getFlatAdvanceBalance(data.flatId);
      this.setFlatAdvanceBalance(data.flatId, currentAdv + advanceAllocated);
    }

    // 4. Insert payment receipt
    const monthDesc = allocatedMonths.length > 0 ? ` for ${allocatedMonths.join(", ")}` : "";
    const newPayment: MaintenancePayment = {
      id: "pay-" + Date.now(),
      flat_id: data.flatId,
      resident_id: flat.current_resident?.id || null,
      receipt_number: receiptNo,
      total_amount_received: data.amountReceived,
      payment_date: data.paymentDate,
      payment_method: data.paymentMethod,
      transaction_ref: data.transactionRef || null,
      description: data.description || `Maintenance payment for flat ${flat.flat_number}${monthDesc}`,
      attachment_url: data.attachmentUrl || null,
      created_by: "admin@gmail.com",
      created_at: new Date().toISOString(),
    };
    payments.unshift(newPayment);
    setStoredItem("payments", payments);

    // 5. Update Society Wallet with single credit
    const walletTransactions = this.getWalletTransactions();
    const lastBal = walletTransactions.length > 0 ? walletTransactions[0].running_balance : 0;
    const newBal = lastBal + data.amountReceived;

    const newTx: WalletTransaction = {
      id: "tx-" + Date.now(),
      society_id: "soc-parijat-a-wing",
      transaction_date: data.paymentDate,
      transaction_type: "CREDIT",
      category: "MAINTENANCE",
      amount: data.amountReceived,
      source_ref_id: newPayment.id,
      running_balance: newBal,
      description: `Maintenance receipt ${receiptNo} (${flat.flat_number}${
        allocatedMonths.length > 0 ? ` - ${allocatedMonths.join(", ")}` : ""
      }${advanceAllocated > 0 ? `, incl. ₹${advanceAllocated} Advance` : ""})`,
      created_at: new Date().toISOString(),
    };
    walletTransactions.unshift(newTx);
    setStoredItem("wallet_transactions", walletTransactions);

    return { payment: newPayment, receiptNo, advanceAllocated, allocatedMonths };
  },

  // --- EXPENSES ---
  getCategories(): ExpenseCategory[] {
    return getStoredItem("expense_categories", initialCategories);
  },
  getExpenses(): SocietyExpense[] {
    const expenses = getStoredItem("expenses", initialExpenses);
    const categories = this.getCategories();
    return expenses.map((exp) => ({
      ...exp,
      category: categories.find((c) => c.id === exp.category_id),
    }));
  },
  addExpense(data: Omit<SocietyExpense, "id" | "society_id" | "created_at" | "updated_at">): SocietyExpense {
    const expenses = this.getExpenses();
    const categories = this.getCategories();
    const cat = categories.find((c) => c.id === data.category_id);

    const newExpense: SocietyExpense = {
      ...data,
      id: "exp-" + Date.now(),
      society_id: "soc-parijat-a-wing",
      category: cat,
      created_at: new Date().toISOString(),
      updated_at: new Date().toISOString(),
    };
    expenses.unshift(newExpense);
    setStoredItem("expenses", expenses);

    // Debit Society Wallet
    const walletTransactions = this.getWalletTransactions();
    const lastBal = walletTransactions.length > 0 ? walletTransactions[0].running_balance : 0;
    const newBal = lastBal - data.amount;

    const newTx: WalletTransaction = {
      id: "tx-" + Date.now(),
      society_id: "soc-parijat-a-wing",
      transaction_date: data.expense_date,
      transaction_type: "DEBIT",
      category: "EXPENSE",
      amount: data.amount,
      source_ref_id: newExpense.id,
      running_balance: newBal,
      description: `Expense: ${data.title} (${cat?.name || "General"})`,
      created_at: new Date().toISOString(),
    };
    walletTransactions.unshift(newTx);
    setStoredItem("wallet_transactions", walletTransactions);

    return newExpense;
  },
  deleteExpense(id: string): void {
    const expenses = this.getExpenses();
    const exp = expenses.find((e) => e.id === id);
    if (!exp) return;

    const filtered = expenses.filter((e) => e.id !== id);
    setStoredItem("expenses", filtered);

    // Reversal credit in wallet
    const walletTransactions = this.getWalletTransactions();
    const lastBal = walletTransactions.length > 0 ? walletTransactions[0].running_balance : 0;
    const newBal = lastBal + exp.amount;

    const newTx: WalletTransaction = {
      id: "tx-" + Date.now(),
      society_id: "soc-parijat-a-wing",
      transaction_date: new Date().toISOString().split("T")[0],
      transaction_type: "CREDIT",
      category: "EXPENSE",
      amount: exp.amount,
      source_ref_id: exp.id,
      running_balance: newBal,
      description: `Reversal of deleted expense: ${exp.title}`,
      created_at: new Date().toISOString(),
    };
    walletTransactions.unshift(newTx);
    setStoredItem("wallet_transactions", walletTransactions);
  },

  // --- WALLET ---
  getWalletTransactions(): WalletTransaction[] {
    return getStoredItem("wallet_transactions", initialWalletTransactions);
  },

  // --- DASHBOARD METRICS ---
  getDashboardMetrics(): DashboardMetrics {
    const floors = this.getFloors();
    const flats = this.getFlats();
    const residents = this.getResidents().filter((r) => r.is_active);
    const payments = this.getPayments();
    const expenses = this.getExpenses();
    const walletTx = this.getWalletTransactions();

    const ownerCount = residents.filter((r) => r.resident_type === "OWNER").length;
    const tenantCount = residents.filter((r) => r.resident_type === "TENANT").length;

    const totalMaintenanceCollected = payments.reduce((sum, p) => sum + Number(p.total_amount_received || 0), 0);
    const totalExpenses = expenses.reduce((sum, e) => sum + Number(e.amount || 0), 0);

    const invoices = this.getInvoices();
    const totalPendingDues = invoices
      .filter((inv) => inv.status === "UNPAID" || inv.status === "PARTIAL")
      .reduce((sum, inv) => sum + Number(inv.due_amount || 0), 0);

    const currentWalletBalance = walletTx.length > 0 ? walletTx[0].running_balance : 0;

    return {
      totalFloors: floors.length,
      totalFlats: flats.length,
      totalResidents: residents.length,
      ownerOccupied: ownerCount,
      rentedFlats: tenantCount,
      totalMaintenanceCollected,
      totalPendingDues,
      totalExpenses,
      previousBalance: 0,
      currentWalletBalance,
      advanceLiability: this.getTotalAdvancePool(),
    };
  },
};
