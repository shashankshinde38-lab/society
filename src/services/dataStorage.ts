const STORAGE_KEY_PREFIX = "parijat_erp_v5_";

function getStoredItem<T>(key: string, defaultValue: T): T {
  if (typeof window === "undefined") return defaultValue;
  try {
    const item = window.localStorage.getItem(STORAGE_KEY_PREFIX + key);
    return item ? JSON.parse(item) : defaultValue;
  } catch {
    return defaultValue;
  }
}

function setStoredItem<T>(key: string, value: T): void {
  if (typeof window === "undefined") return;
  try {
    window.localStorage.setItem(STORAGE_KEY_PREFIX + key, JSON.stringify(value));
  } catch (e) {
    console.error("Storage error:", e);
  }
}

// Generate 12-month calendar slots for all flats for a given year.
// Fresh flats/slots default to NO_DUES (due_amount: 0, paid_amount: 0).
// Dues only accumulate when explicitly generated by admin.
function generateYearlyInvoices(flats: Flat[], year: number = 2026, monthlyAmt: number = 1100): MaintenanceInvoice[] {
  const invoices: MaintenanceInvoice[] = [];

  flats.forEach((flat) => {
    for (let m = 1; m <= 12; m++) {
      const amt = flat.maintenance_override || monthlyAmt;
      invoices.push({
        id: `inv-${flat.id}-${year}-${m}`,
        flat_id: flat.id,
        resident_id: null,
        month: m,
        year,
        invoice_amount: amt,
        paid_amount: 0,
        due_amount: 0, // Starts at 0 until maintenance dues are generated
        status: "NO_DUES", // Default status for new flat: No Dues
        due_date: `${year}-${String(m).padStart(2, "0")}-10`,
        created_at: new Date().toISOString(),
        updated_at: new Date().toISOString(),
      });
    }
  });

  return invoices;
}

